//! Export wrappers and headers (T4-3, spec §14.2): the public C API of each
//! exported flow and function.

use std::fmt::Write as _;

use onsa_core::{FixedField, FnId, Mode, ParamKey, ParamKind, ParamNumber, Ty};

use crate::emit::{Cx, Export, R, f32_lit};
use crate::names::ident;
use onsa_diag::unsupported::Feature;

use crate::{PanicMode, no_span, unsupported};

/// What the header of a flow records of its API, for [`crate::FlowApi`].
pub(crate) struct FlowParts {
    pub init_args: Vec<crate::ApiField>,
    pub params_fields: Vec<crate::ApiField>,
    pub process_args: Vec<crate::IoArg>,
}

/// A number of `@param` in the `float` of the table (§14.2, until W10-03); a
/// `Bool` is the E0200 of [`wrappers`].
fn table_number(n: Option<ParamNumber>) -> R<Option<f64>> {
    match n {
        Some(ParamNumber::Float(x)) => Ok(Some(x)),
        Some(ParamNumber::Int(x)) => Ok(Some(x as f64)),
        Some(ParamNumber::Bool(_)) => Err(crate::emit::internal("a `Bool` value in the table of the parameters")),
        None => Ok(None),
    }
}

/// The public header `onsa_<flow>.h`, and what it declares of the API.
pub(crate) fn header(cx: &mut Cx, e: &Export) -> R<(String, FlowParts)> {
    let meta = &cx.m.flows[e.meta_index];
    let fns = meta.fns.clone();
    let sym = e.symbol.clone();
    let up = e.upper.clone();
    let mut h = String::new();
    let _ = writeln!(h, "/* {sym}.h — generated by onsa build for the flow `{}`; do not edit. */", meta.name);
    let _ = writeln!(h, "#ifndef {up}_H");
    let _ = writeln!(h, "#define {up}_H");
    let _ = writeln!(h, "#include \"{}\"", crate::RUNTIME_HEADER_NAME);
    let _ = writeln!(h, "#ifdef __cplusplus\nextern \"C\" {{\n#endif\n");
    let _ = writeln!(h, "#define {up}_SIZE      {}   /* bytes of the fast region (spec §12.4) */", e.layout.size);
    let _ = writeln!(h, "#define {up}_BULK_SIZE {}   /* bytes of the bulk region */", e.layout.bulk_size);
    let _ = writeln!(h, "#define {up}_ALIGN     {}", e.layout.align);
    let _ = writeln!(h, "#define {up}_PARAM_COUNT {}\n", meta.params.len());
    let _ = writeln!(h, "typedef struct {sym} {sym};   /* the state (fast region); opaque */");
    // Params struct with the input names (spec §14.2).
    let pfields = cx.fields(fns.params).to_vec();
    let _ = write!(h, "typedef struct {sym}_params {{");
    if pfields.is_empty() {
        let _ = write!(h, " uint8_t onsa_empty;");
    }
    let mut params_fields = Vec::new();
    for (name, ty) in &pfields {
        let tn = scalar_c(cx, ty, &format!("the `block` input `{name}`"))?;
        let _ = write!(h, " {tn} {};", ident(name));
        params_fields.push(crate::ApiField { name: name.clone(), c_name: ident(name), c_type: tn });
    }
    let _ = writeln!(h, " }} {sym}_params;\n");
    let cfg = config_args(cx, e)?;
    let _ = writeln!(
        h,
        "/* Memory is the caller's: `s` has {up}_SIZE bytes aligned to {up}_ALIGN, `bulk` has {up}_BULK_SIZE (NULL when 0). */"
    );
    let _ = writeln!(
        h,
        "/* 0: ok, 1: `init` panicked (panic = \"poison\" only): the state is left uninitialized — `process` returns 1\n * and `reset` does nothing until `init` succeeds (spec §14.2, S-27). */"
    );
    let _ = writeln!(h, "int  {sym}_init({sym}* s, void* bulk, {}float sample_rate);", cfg.decls);
    let _ =
        writeln!(h, "void {sym}_reset({sym}* s);   /* clears `_poisoned`; no effect on an uninitialized instance */");
    if fns.params_default.is_some() {
        let _ = writeln!(h, "void {sym}_params_default({sym}_params* p);");
    }
    let io = process_io(cx, e)?;
    let _ = writeln!(
        h,
        "/* 0: ok, 1: poisoned or uninitialized, 2: overlapping buffers that are not an in-place pair (an in-place pair\n * is an input and an output of the same element type at the same pointer). On 1 and 2 all outputs are zero. */"
    );
    let _ = writeln!(h, "int  {sym}_process({sym}* s, const {sym}_params* p, {}uint32_t frames);", io.decls);
    if !meta.params.is_empty() {
        let _ = writeln!(h, "extern const onsa_param_info {sym}_param_info[{}];", meta.params.len());
    }
    if cx.opts.provides_alloc {
        let _ = writeln!(h, "\n/* Convenience on targets with a heap. */");
        let _ = writeln!(
            h,
            "{sym}* {sym}_new({}float sample_rate);   /* NULL when out of memory or `init` panicked */",
            cfg.decls
        );
        let _ = writeln!(h, "void {sym}_free({sym}* s);");
    }
    if cx.opts.panic == PanicMode::Poison {
        let _ = writeln!(
            h,
            "\n/* panic = \"poison\" (spec §9.2): a panic inside `process` zeroes the outputs, poisons the instance\n * (`process` returns 1 until `reset`); a panic inside an exported function returns a zero value and\n * {}() reports it once. */",
            take_panic_name(cx.opts)
        );
        let _ = writeln!(h, "int {}(void);", take_panic_name(cx.opts));
    }
    let _ = writeln!(h, "\n#ifdef __cplusplus\n}}\n#endif");
    let _ = writeln!(h, "#endif /* {up}_H */");
    let process_args = io
        .params
        .into_iter()
        .map(|p| crate::IoArg {
            c_type: cx.names.name(&p.elem),
            name: p.onsa,
            c_name: p.name,
            planar: p.planar,
            output: p.output,
        })
        .collect();
    Ok((h, FlowParts { init_args: cfg.api, params_fields, process_args }))
}

struct ConfigArgs {
    /// `float time, ` (empty when the config has no fields)
    decls: String,
    /// `(name, field)` pairs
    fields: Vec<(String, String)>,
    /// The arguments, for [`crate::FlowApi::init_args`].
    api: Vec<crate::ApiField>,
}

/// The arguments of `_init` and `_new` of the flow of `e`: the inputs of
/// `init`. A C name that is another's there is an E0200 ([`own_names`]).
fn config_args(cx: &mut Cx, e: &Export) -> R<ConfigArgs> {
    let meta = &cx.m.flows[e.meta_index];
    let (fns, at) = (&meta.fns, meta.name_span);
    let fields = cx.fields(fns.config).to_vec();
    let mut decls = String::new();
    let mut out = Vec::new();
    let mut api = Vec::new();
    for (name, ty) in &fields {
        let tn = scalar_c(cx, ty, &format!("the `init` input `{name}`"))?;
        let _ = write!(decls, "{tn} {}, ", ident(name));
        out.push((ident(name), ident(name)));
        api.push(crate::ApiField { name: name.clone(), c_name: ident(name), c_type: tn });
    }
    let of: &[&str] = if cx.opts.provides_alloc { &["_init", "_new"] } else { &["_init"] };
    let user = api.iter().map(|a| (a.c_name.clone(), format!("the `init` input `{}`", a.name))).collect();
    own_names(e, at, of, cx.bulk.contains_key(&fns.state), user)?;
    Ok(ConfigArgs { decls, fields: out, api })
}

fn scalar_c(cx: &mut Cx, ty: &Ty, what: &str) -> R<String> {
    if ty.is_scalar() { Ok(cx.names.name(ty)) } else { Err(unsupported(no_span(), Feature::ExportNonScalar, &[what])) }
}

/// One signal of `process`: a `Span` / planar parameter of the C API.
struct IoParam {
    name: String,
    /// The Onsa name (of the input or the field of the output).
    onsa: String,
    elem: Ty,
    /// `Some(n)`: `[Span[T]; n]` (planar channels)
    planar: Option<u32>,
    output: bool,
}

/// One parameter of the Core `process` after the state and the
/// parameters: the signals `signals` of [`ProcessIo::params`], and the
/// struct of an `In` or `Out` (§11.6) that holds them.
struct IoGroup {
    signals: std::ops::Range<usize>,
    of: Option<onsa_core::TypeId>,
}

struct ProcessIo {
    decls: String,
    params: Vec<IoParam>,
    groups: Vec<IoGroup>,
}

/// The names of the signals of a flow: its `sample` inputs, then its outputs
/// (the fields of a struct), as the C API names them until W10-03 (§14.2).
fn signal_names(meta: &onsa_core::FlowMeta) -> Vec<String> {
    let ins = meta.sig_inputs.iter().map(|(n, _)| n.clone());
    ins.chain(meta.outputs.iter().map(|(n, _, _)| n.clone())).collect()
}

/// The names the wrappers give their own parameters and locals beside the
/// signals and the inputs of `init` (their other locals begin with `onsa_`,
/// as no name of the program does, [`ident`]): (the wrapper, of a flow with
/// a bulk region alone, the name, what it is). The one list the C names of
/// the user are checked against ([`own_names`]); the `sample_rate` of
/// `_init` and `_new` is a name of the flow (E0304).
const WRAPPER_OWN: &[(&str, bool, &str, &str)] = &[
    ("_process", false, "s", "the state"),
    ("_process", false, "p", "the parameters"),
    ("_process", false, "q", "the clamped parameters"),
    ("_process", false, "frames", "the number of frames"),
    ("_init", false, "s", "the state"),
    ("_init", false, "bulk", "the bulk region"),
    ("_init", false, "cfg", "the struct of the `init` inputs"),
    ("_new", false, "s", "the state"),
    ("_new", true, "b", "the bulk region"),
];

/// The C names `user` (with what the user wrote they are of) of the flow of
/// `e` in its wrappers `of`: a name that is another's in one of them is an
/// E0200 at the flow's name until W10-03 names the C API apart (R-15, §14.2).
fn own_names(e: &Export, at: onsa_diag::Span, of: &[&str], bulk: bool, user: Vec<(String, String)>) -> R<()> {
    for &w in of {
        let own = WRAPPER_OWN.iter().filter(|o| o.0 == w && (bulk || !o.1));
        let mut seen: std::collections::HashMap<_, _> =
            own.map(|&(_, _, n, it)| (n.to_string(), format!("{it} `{n}`"))).collect();
        for (c, what) in &user {
            if let Some(other) = seen.insert(c.clone(), what.clone()) {
                let f = format!("{}{w}", e.symbol);
                return Err(unsupported(at, Feature::ApiNames, &[c, &f, &other, what]));
            }
        }
    }
    Ok(())
}

/// The local of the channels of the planar signal `p` in the wrapper.
fn spans_local(p: &IoParam) -> String {
    format!("{}_spans", p.name)
}

/// The signals of the Core `process` (one per `Span` / planar parameter or
/// field of an `In` or `Out`), named by `names` in order. A name that is
/// another of the wrapper's is an E0200 at the flow's name until W10-03
/// names the C API apart (R-15, §14.2).
fn process_io(cx: &mut Cx, e: &Export) -> R<ProcessIo> {
    let m = cx.m;
    let meta = &m.flows[e.meta_index];
    let def = m.fn_(meta.fns.process);
    let names = signal_names(meta);
    let mut names = names.iter();
    let (mut params, mut groups, mut decls) = (Vec::new(), Vec::new(), String::new());
    for p in def.params.iter().skip(2) {
        let output = matches!(p.mode, Mode::Inout);
        let (of, tys) = match &p.ty {
            Ty::Struct(id) => (Some(*id), cx.fields(*id).iter().map(|(_, t)| t.clone()).collect()),
            t => (None, vec![t.clone()]),
        };
        let start = params.len();
        for ty in tys {
            let onsa = names.next().ok_or_else(|| crate::emit::internal("more signals than the flow has"))?.clone();
            let name = ident(&onsa);
            let (elem, planar) = match &ty {
                Ty::Span(e) => ((**e).clone(), None),
                Ty::Array(inner, n) => match &**inner {
                    Ty::Span(e) => ((**e).clone(), Some(*n)),
                    _ => return Err(unsupported(def.span, Feature::ProcessParams, &[])),
                },
                _ => return Err(unsupported(def.span, Feature::ProcessParams, &[])),
            };
            let et = scalar_c(cx, &elem, &format!("the signal `{name}`"))?;
            let c = if output { "" } else { "const " };
            let star = if planar.is_some() { "* const*" } else { "*" };
            let _ = write!(decls, "{c}{et}{star} {name}, ");
            params.push(IoParam { name, onsa, elem, planar, output });
        }
        groups.push(IoGroup { signals: start..params.len(), of });
    }
    if names.next().is_some() {
        return Err(crate::emit::internal("fewer signals than the flow has"));
    }
    let user = params.iter().flat_map(|p| {
        let spans = p.planar.map(|_| (spans_local(p), format!("the channels of the signal `{}`", p.onsa)));
        std::iter::once((p.name.clone(), format!("the signal `{}`", p.onsa))).chain(spans)
    });
    own_names(e, meta.name_span, &["_process"], false, user.collect())?;
    Ok(ProcessIo { decls, params, groups })
}

/// One channel of a signal of `process`: one pointer and its range.
struct IoRange<'a> {
    ptr: String,
    output: bool,
    /// The type of its elements, and its C spelling.
    elem: &'a Ty,
    c_type: String,
}

/// Every channel of every signal of `process` (one range per pointer), from
/// the parameters of the Core `process` (R-141: by structure, not by name).
fn io_ranges<'a>(cx: &mut Cx, io: &'a ProcessIo) -> Vec<IoRange<'a>> {
    let mut ranges = Vec::new();
    for p in &io.params {
        let c_type = cx.names.name(&p.elem);
        let range = |ptr: String| IoRange { ptr, output: p.output, elem: &p.elem, c_type: c_type.clone() };
        match p.planar {
            None => ranges.push(range(p.name.clone())),
            Some(n) => ranges.extend((0..n).map(|k| range(channel_ptr(p, k)))),
        }
    }
    ranges
}

/// The pointer of channel `k` of a planar `[Span[T]; N]` parameter.
fn channel_ptr(p: &IoParam, k: u32) -> String {
    format!("{}[{k}]", p.name)
}

/// `body` guarded by `frames != 0` (S-204: a call of 0 frames reads no signal
/// pointer); nothing when `body` is empty.
fn when_frames(body: &str, indent: &str) -> String {
    if body.is_empty() { String::new() } else { format!("{indent}if (frames != 0) {{\n{body}{indent}}}\n") }
}

/// The statements that zero every channel of every output, all `frames`
/// (R-12, S-199, S-206): every call that does not return 0 outputs silence.
fn zero_lines(cx: &mut Cx, io: &ProcessIo) -> String {
    let mut s = String::new();
    for r in io_ranges(cx, io).iter().filter(|r| r.output) {
        let _ = writeln!(s, "      memset({}, 0, (size_t)frames * sizeof({}));", r.ptr, r.c_type);
    }
    s
}

/// [`zero_lines`] when `frames != 0` (S-204: no pointer is read then).
fn zero_outputs(cx: &mut Cx, io: &ProcessIo) -> String {
    when_frames(&zero_lines(cx, io), "    ")
}

/// The overlap checks (spec §14.2, R-141): every output against every input
/// and every other output, each range measured by its own element type. Two
/// outputs at the same pointer are an error; an input and an output are
/// in place only when their byte ranges are the same. A call that returns 2
/// zeroes every output, where they overlap too, and evaluates nothing (S-206).
fn overlap_checks(cx: &mut Cx, io: &ProcessIo) -> String {
    let ranges = io_ranges(cx, io);
    let mut conds = Vec::new();
    for (i, a) in ranges.iter().enumerate() {
        for b in ranges.iter().skip(i + 1) {
            // S-409: two inputs are not checked (they are only read); every pair with an output is.
            if !(a.output || b.output) {
                continue;
            }
            // S-403: the one pair that may share a pointer is an input and an output of the same
            // element type (in place); any other pair at the same pointer returns 2.
            let in_place = a.output != b.output && a.elem == b.elem;
            let same =
                if in_place { String::new() } else { format!("(const void*){} == (const void*){} || ", a.ptr, b.ptr) };
            conds.push(format!(
                "{same}onsa_overlaps({}, (size_t)frames * sizeof({}), {}, (size_t)frames * sizeof({}))",
                a.ptr, a.c_type, b.ptr, b.c_type
            ));
        }
    }
    if conds.is_empty() {
        return String::new();
    }
    let body = format!("    if ({}) {{\n{}      return 2;\n    }}\n", conds.join(" ||\n        "), zero_lines(cx, io));
    when_frames(&body, "  ")
}

/// The wrappers of one exported flow in the translation unit.
pub(crate) fn wrappers(cx: &mut Cx, e: &Export) -> R<String> {
    let meta = cx.m.flows[e.meta_index].clone();
    let fns = meta.fns.clone();
    let sym = e.symbol.clone();
    let state = cx.names.name(&Ty::Struct(fns.state));
    let config = cx.names.name(&Ty::Struct(fns.config));
    let params = cx.names.name(&Ty::Struct(fns.params));
    let has_bulk = cx.bulk.contains_key(&fns.state);
    let poisoned = cx
        .fields(fns.state)
        .iter()
        .find(|(n, _)| n == FixedField::Poisoned.name())
        .map(|(n, _)| ident(n))
        .ok_or_else(|| crate::emit::internal("flow state without its poisoned field"))?;
    let initialized = cx
        .fields(fns.state)
        .iter()
        .find(|(n, _)| n == FixedField::Initialized.name())
        .map(|(n, _)| ident(n))
        .ok_or_else(|| crate::emit::internal("flow state without its initialized field"))?;
    let mut s = String::new();
    let _ = writeln!(s, "/* ---- export: {} ---- */", meta.name);

    // init
    let cfg = config_args(cx, e)?;
    let _ = writeln!(s, "int {sym}_init({sym}* s, void* bulk, {}float sample_rate) {{", cfg.decls);
    let _ = writeln!(s, "  {config} cfg;");
    let _ = writeln!(s, "  memset(&cfg, 0, sizeof cfg);");
    for (arg, field) in &cfg.fields {
        let _ = writeln!(s, "  cfg.{field} = {arg};");
    }
    if has_bulk {
        let _ = writeln!(s, "  s->bulk = bulk;");
    } else {
        let _ = writeln!(s, "  (void)bulk;");
    }
    if cx.opts.panic == PanicMode::Poison {
        // The state is being built, so the wrapper's own jmp_buf catches the panic (T4-4).
        // The previous slot is restored on every exit so that a wrapper entered from an
        // interrupt (or a nested host call) does not clear the outer wrapper's target (S-26).
        let _ = writeln!(s, "  jmp_buf onsa_jb;");
        let _ = writeln!(s, "  jmp_buf* volatile onsa_prev = onsa_current_jmp;");
        // S-27: a panic inside `init` leaves the instance uninitialized: the whole
        // state (and the bulk region) is zeroed, `_initialized` stays false, 1 is returned.
        let _ = writeln!(s, "  if (setjmp(onsa_jb)) {{");
        let _ = writeln!(s, "    onsa_current_jmp = onsa_prev;");
        if has_bulk {
            let bulk = cx.bulk[&fns.state].struct_name.clone();
            let _ = writeln!(s, "    if (bulk) memset(bulk, 0, sizeof({bulk}));");
        }
        let _ = writeln!(s, "    memset(s, 0, sizeof(*s));");
        if has_bulk {
            let _ = writeln!(s, "    s->bulk = bulk;");
        }
        let _ = writeln!(s, "    return 1;");
        let _ = writeln!(s, "  }}");
        let _ = writeln!(s, "  onsa_current_jmp = &onsa_jb;");
        let _ = writeln!(s, "  {}(s, &cfg, sample_rate);", cx.after_setjmp(fns.init));
        let _ = writeln!(s, "  onsa_current_jmp = onsa_prev;");
    } else {
        let _ = writeln!(s, "  {}(s, &cfg, sample_rate);", cx.fn_name(fns.init));
    }
    let _ = writeln!(s, "  return 0;");
    let _ = writeln!(s, "}}\n");

    // reset
    let _ =
        writeln!(s, "void {sym}_reset({sym}* s) {{ if (!s->{initialized}) return; {}(s); }}\n", cx.fn_name(fns.reset));

    // params_default
    if let Some(pd) = fns.params_default {
        let _ = writeln!(s, "void {sym}_params_default({sym}_params* p) {{ {}(p); }}\n", cx.fn_name(pd));
    }

    // process
    let io = process_io(cx, e)?;
    let _ = writeln!(s, "int {sym}_process({sym}* s, const {sym}_params* p, {}uint32_t frames) {{", io.decls);
    let _ = writeln!(s, "  {params} q;");
    // The order of the entry (spec §14.2, §11.6): a poisoned or uninitialized instance outputs
    // silence and returns 1 (R-12, S-199); the overlap checks (2); then the call. A call of 0
    // frames reads none of the signal pointers (they may be NULL) and checks no overlap (S-204).
    // S-404: an instance that is poisoned or uninitialized returns 1 even when the
    // buffers overlap (the 1 is decided first).
    for p in io.params.iter().filter(|p| p.planar == Some(0)) {
        // `[Span[T]; 0]`: no channel pointer is read (S-407), so the parameter is not referenced.
        let _ = writeln!(s, "  (void){};", p.name);
    }
    if io_ranges(cx, &io).is_empty() {
        // No channel at all (S-407): only the Core `process` reads `frames`, through no span.
        let _ = writeln!(s, "  (void)frames;");
    }
    let zero = zero_outputs(cx, &io);
    let _ = writeln!(s, "  if (!s->{initialized} || s->{poisoned}) {{");
    let _ = writeln!(s, "{zero}    return 1;\n  }}");
    s.push_str(&overlap_checks(cx, &io));
    let _ = writeln!(s, "  q = *p;");
    for (name, ty, pm) in &meta.params {
        let Some(pm) = pm else { continue };
        let (Some(min), Some(max)) = (table_number(pm.number(ParamKey::Min))?, table_number(pm.number(ParamKey::Max))?)
        else {
            continue;
        };
        match ty {
            Ty::Float(onsa_core::FloatKind::F32) => {
                let _ = writeln!(
                    s,
                    "  q.{} = onsa_clamp_f32(q.{}, {}, {});",
                    ident(name),
                    ident(name),
                    f32_lit(min as f32),
                    f32_lit(max as f32)
                );
            }
            Ty::Float(onsa_core::FloatKind::F64) => {
                let _ = writeln!(
                    s,
                    "  q.{} = onsa_clamp_f64(q.{}, {}, {});",
                    ident(name),
                    ident(name),
                    crate::emit::f64_lit(min),
                    crate::emit::f64_lit(max)
                );
            }
            _ => {}
        }
    }
    if cx.opts.panic == PanicMode::Poison {
        // T4-4 (spec §9.2): a panic inside `process` lands here; the outputs
        // are zeroed and the instance is poisoned until `reset`. The jmp_buf
        // is the wrapper's own (S-26): the state layout stays host-independent.
        // The previous slot is restored on every exit so that a wrapper entered from an
        // interrupt (or a nested host call) does not clear the outer wrapper's target (S-26).
        let _ = writeln!(s, "  jmp_buf onsa_jb;");
        let _ = writeln!(s, "  jmp_buf* volatile onsa_prev = onsa_current_jmp;");
        let _ = writeln!(s, "  if (setjmp(onsa_jb)) {{");
        let _ = writeln!(s, "    onsa_current_jmp = onsa_prev;");
        s.push_str(&zero);
        let _ = writeln!(s, "    s->{poisoned} = true;");
        let _ = writeln!(s, "    return 1;");
        let _ = writeln!(s, "  }}");
        let _ = writeln!(s, "  onsa_current_jmp = &onsa_jb;");
    }
    let args = process_args(cx, &io, &mut s);
    // Under poison the call follows the `setjmp`: the guarded twin (R-167).
    let _ = writeln!(s, "  {}({});", cx.after_setjmp(fns.process), args.join(", "));
    if cx.opts.panic == PanicMode::Poison {
        let _ = writeln!(s, "  onsa_current_jmp = onsa_prev;");
    }
    let _ = writeln!(s, "  return 0;");
    let _ = writeln!(s, "}}\n");

    // Parameter metadata table.
    // §14.2: the table writes no truth value as a number; the field of a `Bool` is W10-03's.
    if let Some((name, ..)) = meta.params.iter().find(|(.., p)| p.as_ref().is_some_and(|p| p.kind == ParamKind::Bool)) {
        return Err(unsupported(meta.name_span, Feature::ParamBoolTable, &[name]));
    }
    if !meta.params.is_empty() {
        let _ = writeln!(s, "const onsa_param_info {sym}_param_info[{}] = {{", meta.params.len());
        for (name, _, pm) in &meta.params {
            let f = |k: ParamKey| -> R<String> {
                Ok(table_number(pm.as_ref().and_then(|p| p.number(k)))?
                    .map_or_else(|| "NAN".into(), |x| f32_lit(x as f32)))
            };
            let t = |k: ParamKey| pm.as_ref().and_then(|p| p.text(k)).map(str::to_string);
            let (min, max, def, step, unit, scale, label, id) = match pm {
                Some(_) => (
                    f(ParamKey::Min)?,
                    f(ParamKey::Max)?,
                    f(ParamKey::Default)?,
                    f(ParamKey::Step)?,
                    t(ParamKey::Unit).unwrap_or_default(),
                    t(ParamKey::Scale).unwrap_or_else(|| "linear".into()),
                    t(ParamKey::Label).unwrap_or_default(),
                    t(ParamKey::Id).unwrap_or_else(|| name.clone()),
                ),
                None => (
                    "NAN".into(),
                    "NAN".into(),
                    "NAN".into(),
                    "NAN".into(),
                    String::new(),
                    "linear".into(),
                    String::new(),
                    name.clone(),
                ),
            };
            let _ = writeln!(
                s,
                "  {{ {}, {}, {min}, {max}, {def}, {step}, {}, {}, {} }},",
                crate::emit::c_string(name),
                crate::emit::c_string(&id),
                crate::emit::c_string(&unit),
                crate::emit::c_string(&scale),
                crate::emit::c_string(&label)
            );
        }
        let _ = writeln!(s, "}};\n");
    }

    // _new / _free
    if cx.opts.provides_alloc {
        let _ = writeln!(s, "{sym}* {sym}_new({}float sample_rate) {{", cfg.decls);
        let _ = writeln!(s, "  {sym}* s = ({sym}*)malloc(sizeof({state}));");
        let _ = writeln!(s, "  if (!s) return NULL;");
        if has_bulk {
            let bulk = cx.bulk[&fns.state].struct_name.clone();
            let _ = writeln!(s, "  {{ void* b = malloc(sizeof({bulk})); if (!b) {{ free(s); return NULL; }}");
            let args: Vec<String> = cfg.fields.iter().map(|(a, _)| a.clone()).collect();
            let _ = writeln!(
                s,
                "    if ({sym}_init(s, b, {}sample_rate) != 0) {{ free(b); free(s); return NULL; }} }}",
                args.iter().map(|a| format!("{a}, ")).collect::<String>()
            );
        } else {
            let args: Vec<String> = cfg.fields.iter().map(|(a, _)| a.clone()).collect();
            let _ = writeln!(
                s,
                "  if ({sym}_init(s, NULL, {}sample_rate) != 0) {{ free(s); return NULL; }}",
                args.iter().map(|a| format!("{a}, ")).collect::<String>()
            );
        }
        let _ = writeln!(s, "  return s;");
        let _ = writeln!(s, "}}\n");
        let _ = writeln!(s, "void {sym}_free({sym}* s) {{");
        let _ = writeln!(s, "  if (!s) return;");
        if has_bulk {
            let _ = writeln!(s, "  free(s->bulk);");
        }
        let _ = writeln!(s, "  free(s);");
        let _ = writeln!(s, "}}\n");
    }
    let _ = state;
    Ok(s)
}

/// The arguments of the Core `process` in its wrapper, after the locals
/// that hold them (written to `s`): the views of the signals, and an `In`
/// or `Out` made of them.
fn process_args(cx: &mut Cx, io: &ProcessIo, s: &mut String) -> Vec<String> {
    let mut views = Vec::new();
    for p in &io.params {
        let tag = cx.names.tag(&p.elem);
        let cast = if p.output { String::new() } else { format!("({}*)", cx.names.name(&p.elem)) };
        match p.planar {
            None => views.push(format!("onsa_span_{tag}_of({cast}{}, frames)", p.name)),
            Some(n) => {
                let arr = cx.names.name(&Ty::Array(Box::new(Ty::Span(Box::new(p.elem.clone()))), n));
                let spans = spans_local(p);
                let _ = writeln!(s, "  {arr} {spans};");
                for k in 0..n {
                    // With 0 frames the array of channel pointers is not read (S-204).
                    let _ = writeln!(
                        s,
                        "  {spans}.a[{k}] = onsa_span_{tag}_of({cast}(frames != 0 ? {} : NULL), frames);",
                        channel_ptr(p, k)
                    );
                }
                views.push(spans);
            }
        }
    }
    let mut args = vec!["s".to_string(), "&q".to_string()];
    for (k, g) in io.groups.iter().enumerate() {
        let Some(id) = g.of else {
            // `[Span[T]; N]` parameters are aggregates: borrowed → `const T*`, `inout` → `T*`.
            let one = &io.params[g.signals.start];
            args.push(if one.planar.is_some() {
                format!("&{}", views[g.signals.start])
            } else {
                views[g.signals.start].clone()
            });
            continue;
        };
        // An `In` or `Out` (§11.6), passed as a struct is: by its address.
        let local = format!("onsa_io{k}");
        let _ = writeln!(s, "  {} {local};", cx.names.name(&Ty::Struct(id)));
        let fields: Vec<String> = cx.fields(id).iter().map(|(n, _)| ident(n)).collect();
        for (field, view) in fields.iter().zip(&views[g.signals.clone()]) {
            let _ = writeln!(s, "  {local}.{field} = {view};");
        }
        args.push(format!("&{local}"));
    }
    args
}

/// Header of the exported plain functions (`@export`), and their API
/// (the header name is the caller's).
pub(crate) fn fn_header(cx: &mut Cx, fns: &[FnId], header: &str) -> R<(String, Vec<crate::FnApi>)> {
    let up: String = format!("{}{}", cx.opts.prefix(), ident(&cx.opts.package)).to_ascii_uppercase();
    let mut h = String::new();
    let _ = writeln!(
        h,
        "/* exported functions of package `{}` — generated by onsa build; do not edit. */",
        cx.opts.package
    );
    let _ = writeln!(
        h,
        "#ifndef {up}_FNS_H\n#define {up}_FNS_H\n#include \"{}\"\n#ifdef __cplusplus\nextern \"C\" {{\n#endif\n",
        crate::RUNTIME_HEADER_NAME
    );
    let mut apis = Vec::new();
    for f in fns {
        let sig = fn_signature(cx, *f)?;
        let _ = writeln!(h, "{};", sig.proto);
        apis.push(crate::FnApi {
            fn_: cx.m.fn_(*f).name.clone(),
            symbol: sig.symbol,
            header: header.to_string(),
            params: sig.params,
            ret: sig.ret,
        });
    }
    if cx.opts.panic == PanicMode::Poison {
        let _ = writeln!(
            h,
            "\n/* panic = \"poison\" (spec §9.2): a panic inside an exported function makes it return a zero value;\n * {}() tells whether the last call panicked (and clears the flag). */",
            take_panic_name(cx.opts)
        );
        let _ = writeln!(h, "int {}(void);", take_panic_name(cx.opts));
    }
    let _ = writeln!(h, "\n#ifdef __cplusplus\n}}\n#endif\n#endif");
    Ok((h, apis))
}

/// The signature of an exported function.
struct FnSignature {
    proto: String,
    /// The arguments the wrapper forwards to the inner function.
    fwd: Vec<String>,
    symbol: String,
    params: Vec<crate::FnParam>,
    ret: Option<String>,
}

/// The prototype, the argument forwarding and the API of an exported function.
fn fn_signature(cx: &mut Cx, f: FnId) -> R<FnSignature> {
    let def = cx.m.fn_(f);
    if def.sret || !(def.ret.is_scalar() || def.ret == Ty::Unit) {
        return Err(unsupported(def.span, Feature::ExportAggregateReturn, &[]));
    }
    let short = def.name.rsplit('.').next().unwrap_or(&def.name).to_string();
    let sym = format!("{}{}", cx.opts.prefix(), ident(&short));
    let ret = if def.ret == Ty::Unit { "void".to_string() } else { cx.names.name(&def.ret) };
    let mut decls = Vec::new();
    let mut fwd = Vec::new();
    let mut params = Vec::new();
    for p in &def.params {
        let onsa = def.locals[p.local.0 as usize].name.clone();
        let name = ident(&onsa);
        let field = |c_type: String| crate::ApiField { name: onsa.clone(), c_name: name.clone(), c_type };
        match (&p.ty, p.mode) {
            (t, Mode::Inout) if t.is_scalar() => {
                decls.push(format!("{}* {name}", cx.names.name(t)));
                params.push(crate::FnParam { field: field(cx.names.name(t)), kind: crate::FnParamKind::InoutScalar });
                fwd.push(name);
            }
            (t, _) if t.is_scalar() => {
                decls.push(format!("{} {name}", cx.names.name(t)));
                params.push(crate::FnParam { field: field(cx.names.name(t)), kind: crate::FnParamKind::Scalar });
                fwd.push(name);
            }
            (Ty::Span(e), mode) if e.is_scalar() => {
                let et = cx.names.name(e);
                let tag = cx.names.tag(e);
                let inout = matches!(mode, Mode::Inout);
                let c = if inout { "" } else { "const " };
                decls.push(format!("{c}{et}* {name}, uint32_t {name}_len"));
                params.push(crate::FnParam { field: field(et.clone()), kind: crate::FnParamKind::Span { inout } });
                fwd.push(format!("onsa_span_{tag}_of(({et}*){name}, {name}_len)"));
            }
            _ => {
                return Err(unsupported(def.span, Feature::ExportParam, &[&name]));
            }
        }
    }
    let plist = if decls.is_empty() { "void".into() } else { decls.join(", ") };
    let proto = format!("{ret} {sym}({plist})");
    let ret = if def.ret == Ty::Unit { None } else { Some(ret) };
    Ok(FnSignature { proto, fwd, symbol: sym, params, ret })
}

pub(crate) fn fn_wrapper(cx: &mut Cx, f: FnId) -> R<String> {
    let FnSignature { proto, fwd, .. } = fn_signature(cx, f)?;
    let def = cx.m.fn_(f);
    let inner = cx.fn_name(f).to_string();
    let mut s = String::new();
    let _ = writeln!(s, "/* ---- export: {} ---- */", def.name);
    let _ = writeln!(s, "{proto} {{");
    if cx.opts.panic == PanicMode::Poison {
        // T4-4 (spec §9.2): panics do not cross the FFI boundary; the call
        // returns a zero value and `<prefix>take_panic()` reports it.
        let ret = if def.ret == Ty::Unit { None } else { Some(cx.names.name(&def.ret)) };
        // The previous slot is restored on every exit so that a wrapper entered from an
        // interrupt (or a nested host call) does not clear the outer wrapper's target (S-26).
        let _ = writeln!(s, "  jmp_buf onsa_jb;");
        let _ = writeln!(s, "  jmp_buf* volatile onsa_prev = onsa_current_jmp;");
        match &ret {
            Some(r) => {
                let _ = writeln!(s, "  {r} onsa_r;");
                let _ = writeln!(
                    s,
                    "  if (setjmp(onsa_jb)) {{ onsa_current_jmp = onsa_prev; onsa_last_panic = 1; memset(&onsa_r, 0, sizeof onsa_r); return onsa_r; }}"
                );
            }
            None => {
                let _ = writeln!(
                    s,
                    "  if (setjmp(onsa_jb)) {{ onsa_current_jmp = onsa_prev; onsa_last_panic = 1; return; }}"
                );
            }
        }
        let _ = writeln!(s, "  onsa_current_jmp = &onsa_jb;");
        match &ret {
            Some(_) => {
                let _ = writeln!(s, "  onsa_r = {}({});", cx.after_setjmp(f), fwd.join(", "));
                let _ = writeln!(s, "  onsa_current_jmp = onsa_prev;");
                let _ = writeln!(s, "  return onsa_r;");
            }
            None => {
                let _ = writeln!(s, "  {}({});", cx.after_setjmp(f), fwd.join(", "));
                let _ = writeln!(s, "  onsa_current_jmp = onsa_prev;");
            }
        }
    } else if def.ret == Ty::Unit {
        let _ = writeln!(s, "  {inner}({});", fwd.join(", "));
    } else {
        let _ = writeln!(s, "  return {inner}({});", fwd.join(", "));
    }
    let _ = writeln!(s, "}}\n");
    Ok(s)
}

/// The name of `<prefix>take_panic`, how an exported function reports a
/// panic in this version (W10-03 removes it): the one place that makes it,
/// for the headers, the definition and [`crate::CUnit::take_panic`].
pub(crate) fn take_panic_name(opts: &crate::EmitOptions) -> String {
    format!("{}take_panic", opts.prefix())
}

/// `<prefix>take_panic` and its flag (one per translation unit, T4-4).
pub(crate) fn take_panic(cx: &Cx) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "/* ---- panic = \"poison\": the last exported function call panicked (spec §9.2) ---- */");
    let _ = writeln!(s, "static ONSA_THREAD_LOCAL int onsa_last_panic = 0;");
    let _ = writeln!(
        s,
        "int {}(void) {{ int p = onsa_last_panic; onsa_last_panic = 0; return p; }}\n",
        take_panic_name(cx.opts)
    );
    s
}
