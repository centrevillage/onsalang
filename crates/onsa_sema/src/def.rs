//! Definitions: every named item of every module, in one arena (`DefId`).
//! Signatures are lowered here (T2-2); bodies are checked by T2-5 onwards.

use onsa_diag::Span;
use onsa_syntax::ast::{ExprId, ItemId, Mode, Vis};

use crate::ty::{EffectSet, Rate, TyId};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct DefId(pub u32);

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct ModId(pub u32);

/// What a bound is in this version (§6.3, §4.6): a trait of the provisional
/// rows of [`TRAITS`] (S-72; user traits are phase 2), or a kind constraint.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Bound {
    Num,
    Float,
    PartialEq,
    PartialOrd,
    Eq,
    Ord,
    Copy,
    Dup,
    Hash,
    Show,
    Default,
}

/// The operator traits and the standard traits (§6.3), names of the prelude
/// (§15.1, S-107): the one table of their names. Each row has the bound the
/// trait is in this version (S-72), or `None` when a bound of it is an E0200
/// (the operator and number traits W5-05, `Ordinal` W5-06).
pub const TRAITS: [(&str, Option<Bound>); 34] = [
    ("Add", None),
    ("Sub", None),
    ("Mul", None),
    ("Div", None),
    ("Rem", None),
    ("Neg", None),
    ("PartialEq", Some(Bound::PartialEq)),
    ("PartialOrd", Some(Bound::PartialOrd)),
    ("BitAnd", None),
    ("BitOr", None),
    ("BitXor", None),
    ("Shl", None),
    ("Shr", None),
    ("Not", None),
    ("WrappingAdd", None),
    ("WrappingSub", None),
    ("WrappingMul", None),
    ("SaturatingAdd", None),
    ("SaturatingSub", None),
    ("SaturatingMul", None),
    ("Eq", Some(Bound::Eq)),
    ("Ord", Some(Bound::Ord)),
    ("Hash", Some(Bound::Hash)),
    ("Show", Some(Bound::Show)),
    ("Default", Some(Bound::Default)),
    ("Iter", None),
    ("IntoIter", None),
    ("Drop", None),
    ("AnyNum", None),
    ("Num", Some(Bound::Num)),
    ("Float", Some(Bound::Float)),
    ("Int", None),
    ("Unsigned", None),
    ("Ordinal", None),
];

impl Bound {
    /// The name of the bound: of its row of [`TRAITS`], or of the kind
    /// constraint (§4.6).
    pub fn name(self) -> &'static str {
        match self {
            Bound::Copy => onsa_syntax::foreign::COPY,
            Bound::Dup => onsa_syntax::foreign::DUP,
            b => match TRAITS.iter().find(|(_, t)| *t == Some(b)) {
                Some((name, _)) => name,
                None => onsa_diag::internal::bug(None, format!("the bound {b:?} is in no row of the traits")),
            },
        }
    }
}

#[derive(Debug, Clone)]
pub enum GenericKind {
    /// `T`, `T: Num`, `T: ?Dup` (`dup == false` lifts the implicit `Dup` bound, §4.5).
    /// `unknown`: a bound is a name the names stage holds as an error (§18.1,
    /// S-689): `T` satisfies every bound, and its methods are not known.
    Type { bounds: Vec<Bound>, dup: bool, unknown: bool },
    /// `const N: U32`
    Const(TyId),
    /// `e` (effect-row variable)
    Effect,
}

#[derive(Debug, Clone)]
pub struct GenericDef {
    pub name: String,
    pub span: Span,
    pub kind: GenericKind,
}

#[derive(Debug, Clone)]
pub struct ParamSig {
    pub name: String,
    pub mode: Mode,
    pub ty: TyId,
    pub span: Span,
}

#[derive(Debug, Clone)]
pub struct FnDef {
    pub generics: Vec<GenericDef>,
    /// `self` receiver mode, for methods.
    pub self_mode: Option<Mode>,
    pub params: Vec<ParamSig>,
    pub ret: TyId,
    pub rt: bool,
    pub effects: EffectSet,
    /// `None` for `target` declarations and generated flow functions.
    pub body: Option<ExprId>,
    /// `target fn`: the backend provides the body (§15.2, D-07).
    pub target: bool,
    /// Generated by a flow (§11.6); which one.
    pub flow_fn: Option<FlowFn>,
    /// `@fp(relaxed)` (§15.5): its floating-point operations may be contracted and reassociated.
    pub fp_relaxed: bool,
}

/// Functions generated for a flow (§11.6).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FlowFn {
    Init,
    Reset,
    Process,
    ProcessInplace,
    Render,
    ParamsDefault,
}

#[derive(Debug, Clone)]
pub struct FieldDef {
    pub name: String,
    pub ty: TyId,
    /// The visibility the field has: `priv` when written so, else the
    /// struct's (§15.1, S-35).
    pub vis: Vis,
    pub span: Span,
}

#[derive(Debug, Clone)]
pub enum Fields {
    Named(Vec<FieldDef>),
    /// `target type` / `extern` opaque types, and flow `State` until M3.
    Opaque,
}

/// The traits derived at the head of a type (§6.4; S-13: `Hash`, `Show` and `Ordinal` are E0200 in phase 1).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Derive {
    PartialEq,
    Eq,
    PartialOrd,
    Ord,
    Default,
}

#[derive(Debug, Clone)]
pub struct StructDef {
    pub generics: Vec<GenericDef>,
    pub fields: Fields,
    /// The traits derived at the head (§6.4); `None` when an attribute of
    /// the declaration was not read and the list is not known (§18.1, S-460).
    pub derives: Option<Vec<Derive>>,
    /// Generated by a flow (§11.6): which type.
    pub flow_ty: Option<FlowTy>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FlowTy {
    State,
    Config,
    Params,
    Out,
}

impl FlowTy {
    /// The rate of the inputs whose fields it holds (§11.6).
    pub fn input_rate(self) -> Option<Rate> {
        match self {
            FlowTy::Config => Some(Rate::Init),
            FlowTy::Params => Some(Rate::Ctl),
            FlowTy::State | FlowTy::Out => None,
        }
    }
}

#[derive(Debug, Clone)]
pub struct VariantDef {
    pub name: String,
    pub fields: Vec<TyId>,
    pub span: Span,
}

#[derive(Debug, Clone)]
pub struct EnumDef {
    pub generics: Vec<GenericDef>,
    pub variants: Vec<VariantDef>,
    /// As [`StructDef::derives`].
    pub derives: Option<Vec<Derive>>,
}

#[derive(Debug, Clone)]
pub struct ConstDef {
    pub ty: TyId,
    /// `None` inside a `trait`, and for generated `SIZE` / `BULK_SIZE` (M3).
    pub value: Option<ExprId>,
    /// The value when the initializer is an integer literal (array lengths, §4.1).
    pub int_value: Option<u64>,
}

#[derive(Debug, Clone)]
pub struct ImplDef {
    pub generics: Vec<GenericDef>,
    pub self_ty: TyId,
    /// Methods and associated functions, in order.
    pub fns: Vec<DefId>,
    pub consts: Vec<DefId>,
}

/// `@param(...)` metadata (§11.7). Numeric values are evaluated from literals,
/// as values of the input's type (`onsa_syntax::float_value`: an `F32` value
/// is held exactly in the `f64`).
#[derive(Debug, Clone)]
pub struct ParamMeta {
    /// The width of the input's type the numbers are values of (`F64` for
    /// an integer input, whose values every `f64` here holds).
    pub width: onsa_syntax::FloatWidth,
    pub min: Option<f64>,
    pub max: Option<f64>,
    pub default: Option<f64>,
    pub step: Option<f64>,
    pub unit: Option<String>,
    pub scale: Option<String>,
    pub label: Option<String>,
    pub id: Option<String>,
    pub span: Span,
}

impl ParamMeta {
    pub fn empty(span: Span, width: onsa_syntax::FloatWidth) -> ParamMeta {
        ParamMeta {
            width,
            min: None,
            max: None,
            default: None,
            step: None,
            unit: None,
            scale: None,
            label: None,
            id: None,
            span,
        }
    }
}

#[derive(Debug, Clone)]
pub struct FlowInput {
    pub name: String,
    pub rate: Rate,
    /// Value type (without the rate).
    pub ty: TyId,
    pub param: Option<ParamMeta>,
    pub span: Span,
    /// The name, which a binding of the body is declared at (§5.1).
    pub name_span: Span,
}

#[derive(Debug, Clone)]
pub struct FlowDef {
    pub inputs: Vec<FlowInput>,
    /// Output value type (rate is always `Sig`, §11.6).
    pub out: TyId,
    pub body: ExprId,
    /// Generated namespace items (§11.6): `State`, `Config`, ..., `process`, ...
    pub members: Vec<(String, DefId)>,
}

#[derive(Debug, Clone)]
pub enum DefKind {
    Fn(FnDef),
    Flow(FlowDef),
    Struct(StructDef),
    Enum(EnumDef),
    /// `type A = B`, expanded.
    Alias(TyId),
    Const(ConstDef),
    Impl(ImplDef),
    /// `test "name" { }`
    Test {
        name: String,
        body: ExprId,
    },
    /// An `effect` of std (§8.1, D-08, S-659), with no operations in this
    /// version: whether it is `blocking` is recorded, and nothing is computed
    /// from it (E0904, E0905 in phase 2). A user `effect` is `Unsupported`.
    Effect {
        blocking: bool,
    },
    /// A declaration phase 1 does not support (E0200 reported); kept so that
    /// names resolve without cascading errors, with the kind of its name its
    /// keyword tells (§18.1, S-719, S-721).
    Unsupported(Declared),
}

/// The kind of the name of a declaration this version does not support, as
/// its keyword tells (§18.1): what is not read of it (the members of a
/// trait or an effect, the signature of an `extern` function) is an error
/// with no diagnostic where it is used.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Declared {
    Trait,
    Effect,
    Handler,
    /// A function of an `extern` block, a value of the error type.
    Fn,
    /// A type of an `extern` block (opaque).
    Type,
    /// The `extern` block itself, which has no name.
    Block,
}

#[derive(Debug, Clone)]
pub struct Def {
    pub name: String,
    pub module: ModId,
    pub vis: Vis,
    pub span: Span,
    /// Span of the name, for diagnostics.
    pub name_span: Span,
    pub kind: DefKind,
    /// The AST item, when the def comes from source.
    pub item: Option<ItemId>,
    /// `impl` block or flow that owns this def.
    pub owner: Option<DefId>,
}

impl Def {
    pub fn as_fn(&self) -> Option<&FnDef> {
        match &self.kind {
            DefKind::Fn(f) => Some(f),
            _ => None,
        }
    }

    pub fn as_struct(&self) -> Option<&StructDef> {
        match &self.kind {
            DefKind::Struct(s) => Some(s),
            _ => None,
        }
    }

    pub fn as_enum(&self) -> Option<&EnumDef> {
        match &self.kind {
            DefKind::Enum(e) => Some(e),
            _ => None,
        }
    }

    pub fn as_flow(&self) -> Option<&FlowDef> {
        match &self.kind {
            DefKind::Flow(f) => Some(f),
            _ => None,
        }
    }

    /// Generic parameters of the def itself (not of its owner).
    pub fn generics(&self) -> &[GenericDef] {
        match &self.kind {
            DefKind::Fn(f) => &f.generics,
            DefKind::Struct(s) => &s.generics,
            DefKind::Enum(e) => &e.generics,
            DefKind::Impl(i) => &i.generics,
            _ => &[],
        }
    }
}
