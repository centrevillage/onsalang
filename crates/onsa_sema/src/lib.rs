/// One parsed source file (spec §15.1: one file = one module).
#[derive(Debug)]
pub struct Module {
    /// Module path from the package root, a name for each part (S-313):
    /// `["dsp", "voice"]` for `dsp/voice.onsa`. A part is the name of a
    /// directory or the file's name without `.onsa`, not split at a `.`
    /// (`a.b.onsa` is `["a.b"]`, another module than `a/b.onsa`, R-46).
    pub segments: Vec<String>,
    pub file: FileId,
    pub text: String,
    pub parsed: Parsed,
}

impl Module {
    /// The module path as diagnostics show it: `dsp.voice`.
    pub fn path(&self) -> String {
        self.segments.join(".")
    }
}

/// Which package the driver loaded: the embedded std or an ordinary one
/// (R-88 (1)). The privileges of std (the effects phase 1 does not implement,
/// D-08; `target` declarations, D-07) read this, not the package's name.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PackageRole {
    Std,
    Ordinary,
}

/// A package: its modules and the packages it depends on (spec §15.1, §15.3).
///
/// The dependencies are the table of the packages visible to this one, the
/// implicit `std` included; each is visible by its name (in this version a
/// key of `[dependencies]` is a package name). They are shared: a package
/// that two others depend on is one value, which [`flatten`] lists, and so
/// analysis reads, once (R-88 (1)). Making one value of one package is the
/// driver's, which builds the graph once (design 3.3).
#[derive(Debug)]
pub struct Package {
    pub name: String,
    pub modules: Vec<Module>,
    pub deps: Vec<Arc<Package>>,
    pub role: PackageRole,
}

impl Package {
    /// An ordinary package.
    pub fn new(name: impl Into<String>, modules: Vec<Module>, deps: Vec<Arc<Package>>) -> Package {
        Package { name: name.into(), modules, deps, role: PackageRole::Ordinary }
    }

    /// The embedded std: no dependencies.
    pub fn std(modules: Vec<Module>) -> Package {
        Package { name: STD_PACKAGE.into(), modules, deps: Vec::new(), role: PackageRole::Std }
    }
}

/// The name of the embedded standard library's package.
pub const STD_PACKAGE: &str = "std";

/// The version of the embedded std (§15.3), which `onsa --version` shows and
/// a `std = "x.y.z"` entry is compared with (W4-02).
// SPEC-GAP(S-626): the spec does not fix the value; it is the compiler's version.
pub const STD_VERSION: &str = env!("CARGO_PKG_VERSION");

/// One module of the embedded std.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct StdModule {
    /// The module path under `std`, a name for each part: `["dsp", "test"]`.
    pub segments: &'static [&'static str],
    /// The file under `std/`, `/` between the parts: `dsp/test.onsa`.
    pub file: &'static str,
    pub text: &'static str,
}

/// The modules of the embedded std, generated by `build.rs` from the files
/// under `std/` (R-80 (4)), in the order of their paths. Embedded, so that
/// `wasm32` builds need no file I/O.
pub fn std_modules() -> &'static [StdModule] {
    const STD: &[StdModule] = include!(concat!(env!("OUT_DIR"), "/std_modules.rs"));
    STD
}

/// Packages in analysis order: dependencies first (depth-first), the package
/// itself last, each package once however many packages depend on it.
/// `ModInfo::pkg`, the package's ID, indexes this list. A package is the same
/// one when it is the same value (the driver shares it); the graph has no
/// cycle, since a package's dependencies are made before it and do not change.
pub fn flatten(pkg: &Package) -> Vec<&Package> {
    fn go<'a>(p: &'a Package, seen: &mut HashSet<*const Package>, out: &mut Vec<&'a Package>) {
        for d in &p.deps {
            if seen.insert(Arc::as_ptr(d)) {
                go(d, seen, out);
            }
        }
        out.push(p);
    }
    let mut out = Vec::new();
    let mut seen = HashSet::new();
    go(pkg, &mut seen, &mut out);
    out
}

/// Result of analysis (T2-1 .. T2-4). Everything the body checker needs.
#[derive(Debug, Default)]
pub struct Analysis {
    pub modules: Modules,
    pub defs: Vec<Def>,
    pub types: Types,
    /// Prelude and builtin type names (§15.1): the compiler's, and the
    /// items of `std.core` (S-659).
    pub prelude: HashMap<String, Entity>,
    /// The effect `Alloc` of `std.core`, a lang item (D-08): the one effect
    /// of an effect row phase 1 gives a meaning (`crate::sig::read_effects`).
    pub alloc: Option<DefId>,
    /// `TyId` keys of generic builtins in `Modules::assoc_builtin`.
    pub builtin_key: HashMap<ty::BuiltinTy, TyId>,
    /// The names of each body, resolved by the names stage
    /// ([`names::body::walk_bodies`]).
    pub(crate) names: HashMap<DefId, names::body::BodyNames>,
    /// The order of the declarations of types and their cycles (E0311,
    /// `sig::decls`).
    pub(crate) decls: sig::Decls,
    /// Typed bodies of functions, tests and `const` initializers (T2-5).
    pub bodies: HashMap<DefId, BodyInfo>,
    /// Values of `const` items evaluated at check time (T2-11).
    pub const_values: HashMap<DefId, ConstValue>,
    /// Typed and rated flow bodies (T3-1), the input of flow lowering (T3-5).
    pub flows: HashMap<DefId, FlowInfo>,
    /// The defs of failed items (`onsa_syntax::ast::Item::failed`, S-59):
    /// their bodies are not checked, and a use of what was not read gets no
    /// diagnostic (R-71, S-260). A name the names stage holds as an error is
    /// no error of its unit (§18.1, S-692): it leaves no mark here.
    pub failed: HashMap<DefId, onsa_syntax::ast::Failed>,
    /// The defs whose signature or declaration reads what the check does not
    /// read and gets no diagnostic for it: a name the names stage holds as an
    /// error, by its spelling (`Self::record_if_held`) or as a path
    /// (`Self::unread_path`), or a member of a def a syntax error cut. Their
    /// check goes on (§18.1, S-692), and a fix of the name can show an error
    /// they did not report. A read in a body marks the body instead
    /// ([`BodyInfo::read_unread`]).
    pub read_held: HashSet<DefId>,
    pub diagnostics: Vec<Diagnostic>,
    /// The diagnostics of the paths of the modules, outside every unit (the
    /// E0304 of a module under the root of the name of a package, §15.1):
    /// each is reported, as those of the input's paths. Those the driver
    /// makes from the paths of the files (`Loaded::input_diagnostics`)
    /// meet these at one place, `onsa_driver::analyze`: two paths, as they
    /// are made at two stages (the files read, the table of the heads).
    pub path_diagnostics: Vec<Diagnostic>,
    /// The names the stages resolved, each as the name of its declaration
    /// and the name that names it (§2.3, S-82): what the candidate of an
    /// E0320 renames ([`rename_fixes`]). A cell, as the one resolution of a
    /// path ([`Analysis::typed_members`]) reads the analysis.
    pub(crate) uses: std::cell::RefCell<Vec<(onsa_diag::Span, onsa_diag::Span)>>,
}

impl Analysis {
    pub fn def(&self, id: DefId) -> &Def {
        &self.defs[id.0 as usize]
    }

    pub fn defs_of_module(&self, m: ModId) -> impl Iterator<Item = (DefId, &Def)> {
        self.defs.iter().enumerate().filter(move |(_, d)| d.module == m).map(|(i, d)| (DefId(i as u32), d))
    }

    /// The parsed AST of a module, given the package that was analyzed.
    pub fn ast<'a>(&self, pkg: &'a Package, m: ModId) -> Option<&'a Module> {
        let info = self.modules.get(m);
        flatten(pkg).get(info.pkg).and_then(|p| info.module.and_then(|i| p.modules.get(i)))
    }

    /// Module of a file, if the file is one.
    pub fn module_of_file(&self, file: FileId) -> Option<ModId> {
        self.modules.mods.iter().position(|m| m.file == Some(file)).map(|i| ModId(i as u32))
    }

    /// Resolve a path from inside module `from`.
    pub fn resolve_path(&self, from: ModId, path: &onsa_syntax::ast::Path) -> Result<Entity, ResolveError> {
        self.modules.resolve_path(from, path, (&self.prelude, &self.defs, &self.builtin_key))
    }

    /// Whether the path names what the names stage holds as an error (§18.1,
    /// S-462, S-675), and if it does, records `def` in [`Self::read_held`]
    /// (the side effect). The one test of the places of `def` that read a
    /// name by its spelling and do not resolve it (an effect, a bound, a
    /// derived trait): there, such a name gets no diagnostic either.
    pub(crate) fn record_if_held(&mut self, def: DefId, from: ModId, path: &onsa_syntax::ast::Path) -> bool {
        let held = matches!(self.resolve_path(from, path), Err(ResolveError::Failed));
        if held {
            self.read_held.insert(def);
        }
        held
    }

    /// Whether the path that did not resolve (`err`) names what the check
    /// does not read (§18.1): a name the names stage holds as an error
    /// (S-462, S-675) or a member of a def a syntax error cut or of an alias
    /// of the error type ([`Self::through_partly_read`]). Such a path gets no
    /// diagnostic: the error type in a type place, the end of the check of
    /// the body in a value place (S-692). If it is one, records `def` in
    /// [`Self::read_held`] (the side effect).
    pub(crate) fn unread_path(
        &mut self,
        def: DefId,
        from: ModId,
        path: &onsa_syntax::ast::Path,
        err: &ResolveError,
    ) -> bool {
        let unread = self.unread(from, path, err);
        if unread {
            self.read_held.insert(def);
        }
        unread
    }

    /// Whether the path that did not resolve (`err`) names what the check
    /// does not read, as of [`Self::unread_path`], which records it.
    pub(crate) fn unread(&self, from: ModId, path: &onsa_syntax::ast::Path, err: &ResolveError) -> bool {
        *err == ResolveError::Failed || self.through_partly_read(from, path)
    }

    /// Fully qualified name of a def (`dsp.voice.State`), for diagnostics.
    pub fn qualified_name(&self, id: DefId) -> String {
        let def = self.def(id);
        let mut parts = Vec::new();
        if let Some(owner) = def.owner {
            parts.push(self.qualified_name(owner));
        } else {
            let m = self.modules.get(def.module);
            if !m.path.is_empty() {
                parts.push(m.path.clone());
            }
        }
        parts.push(def.name.clone());
        parts.join(".")
    }

    /// The name of a def as its module writes it: of an item a flow
    /// generates, with the flow (`voice.State`).
    pub fn shown_name(&self, id: DefId) -> String {
        let def = self.def(id);
        match def.owner {
            Some(o) if matches!(self.def(o).kind, DefKind::Flow(_)) => format!("{}.{}", self.def(o).name, def.name),
            _ => def.name.clone(),
        }
    }

    /// Render a type with user types by their short names.
    pub fn display_type(&self, ty: TyId) -> String {
        self.types.display(ty, &|d| self.def(d).name.clone(), &|i| format!("<{i}>"))
    }

    /// The def is of an item whose heading a syntax error cut
    /// ([`onsa_syntax::ast::Failed::Heading`]): a function of it is an error
    /// to its users (a call of it is not checked against it).
    pub fn heading_failed(&self, id: DefId) -> bool {
        self.failed.get(&id) == Some(&onsa_syntax::ast::Failed::Heading)
    }

    /// The def is of an item a syntax error cut before its end
    /// ([`onsa_syntax::ast::Failed::Body`] or `Heading`): some of its fields,
    /// variants or value were not read, and their uses get no diagnostic
    /// (S-260). An item read whole whose unit has another syntax error
    /// (`Failed::Unit`) is not one.
    pub fn partly_read(&self, id: DefId) -> bool {
        matches!(self.failed.get(&id), Some(onsa_syntax::ast::Failed::Body | onsa_syntax::ast::Failed::Heading))
    }

    /// The longest prefix of `path` that names a def names a def a syntax
    /// error cut (S-260) or an alias of the error type (§18.1, R-271): the
    /// rest of the path is not known, and a path that does not resolve gets
    /// no diagnostic (R-71).
    pub fn through_partly_read(&self, from: ModId, path: &onsa_syntax::ast::Path) -> bool {
        for k in (1..path.segments.len()).rev() {
            let prefix = onsa_syntax::ast::Path { segments: path.segments[..k].to_vec(), span: path.span };
            if let Ok(Entity::Def(d)) = self.resolve_path(from, &prefix) {
                return self.partly_read(d) || self.error_alias(d);
            }
        }
        false
    }

    /// The def is an alias of the error type (§18.1, R-271): a struct, a
    /// variant or a member written through it is not known.
    pub fn error_alias(&self, id: DefId) -> bool {
        matches!(self.def(id).kind, DefKind::Alias(t) if matches!(self.types.get(t), Ty::Error))
    }

    pub fn kind_of(&self, ty: TyId) -> Option<Kind> {
        kind::kind_of(self, ty)
    }

    pub fn layout_of(&self, ty: TyId) -> Option<Layout> {
        layout::layout_of(self, ty)
    }
}

/// Analyze a package and its dependencies (T2-1 .. T2-4).
pub fn analyze(pkg: &Package) -> Analysis {
    let mut analysis = sig::collect_and_lower(pkg);
    check_bodies(pkg, &mut analysis);
    analysis
}

/// Body checking (T2-5 .. T2-12): type inference per spec §4.7, generics
/// instantiation, second-class values and closures, argument modes and
/// exclusivity, `rt` rules, scopes / shadowing (E0304), `const` evaluation,
/// typed holes. It gets: `Analysis.defs` (every fn with `FnDef.body`, every
/// flow with `FlowDef.body`, tests), `Analysis.types`, the scopes in
/// `Analysis.modules` (`resolve_path` for paths in expressions; `Field`
/// chains whose head is a module / flow / type name must be read as paths),
/// `Analysis.modules.assoc` for methods and associated items, `kind_of`
/// and `layout_of`. Diagnostics are pushed to `Analysis.diagnostics`; the
/// driver keeps the first per item (P-01).
pub fn check_bodies(pkg: &Package, analysis: &mut Analysis) {
    names::body::walk_bodies(pkg, analysis);
    body::check_all(pkg, analysis);
    let moved = modes::check_all(pkg, analysis);
    rt::check_all(pkg, analysis, &moved);
    effects::check_all(pkg, analysis, &moved);
}

/// The module (file) a def was declared in.
pub(crate) fn module_of_def<'p>(pkg: &'p Package, a: &Analysis, id: DefId) -> Option<&'p Module> {
    let info = a.modules.get(a.def(id).module);
    flatten(pkg).get(info.pkg).and_then(|p| info.module.and_then(|i| p.modules.get(i)))
}
